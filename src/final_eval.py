"""
Final evaluation: Select best candidate for each run using validation score, 
evaluate best candidate on test set (in-distribution and out-of-distribution)
and compares between methods and baselines.

Read the candidate logs:
    <runs-dir>/candidates_<prefix>_A[_s<seed>]_<timestamp>.jsonl
    <runs-dir>/candidates_<prefix>_B_T<temp>[_s<seed>]_<timestamp>.jsonl

1. Selection per run:
- from valid candidates, remove duplicates
- from top TOP_K candidates by train score, select the candidate with the lowest val score.
- Note: Best Fit (generation 0) is included in the pool.
2. Test the selected heuristics and FF/BF/tuned ABFF on in-distribution test and out-of-distribution test.

Outputs:
    table_excess_by_family.csv      % excess over lower bound, per family
    table_bins_vs_bestfit.csv       total bins minus Best Fit, per family
    table_cost.csv                  discovery cost + execution time
    fig_bins_vs_bf.png              bins vs Best Fit per family, one point per run
    fig_best_so_far.png             best-so-far train score vs cumulative tokens
    heuristics/<run>.py             selected heuristic for each run

Usage (from project root):
    python -m src.final_eval --runs-dir outputs/final_experiment --prefix final
"""

import argparse
import json
import re
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import pandas as pd

from src.baselines import best_fit, first_fit, load_tuned_ab_first_fit
from src.evaluation import evaluate
from src.generate_instances import load_dataset
from src.prompts.method_a import STARTING_PROGRAM
from src.sandbox import run_candidate

ROOT = Path(__file__).resolve().parent.parent
TOP_K = 5
TIMEOUT = 120.0
TEST_SPLITS = ("in-test", "out-test")
LOG_NAME = re.compile(
    r"^candidates_(?P<prefix>.+?)_(?P<method>[AB])(?:_T(?P<temp>[0-9.]+))?"
    r"(?:_s(?P<seed>\d+))?_(?P<timestamp>\d{8}_\d{6})\.jsonl$"
)
COLORS = {"A": "#0072B2", "B": "#D55E00"}


def find_runs(runs_dir, prefix):
    runs = []
    for path in sorted(Path(runs_dir).glob(f"candidates_{prefix}_*.jsonl")):
        m = LOG_NAME.match(path.name)
        if not m or m["prefix"] != prefix:
            continue
        with open(path, encoding="utf-8") as f:
            records = [json.loads(line) for line in f if line.strip()]
        runs.append(
            {
                "method": m["method"],
                "temp": m["temp"],
                "seed": m["seed"],
                "timestamp": m["timestamp"],
                "records": sorted(records, key=lambda r: r["generation"]),
            }
        )
    count = {}
    for r in sorted(runs, key=lambda r: r["timestamp"]):
        # Same naming as run_experiment: A, or B_T<temp> for Method B
        group = f"{r['method']}_T{r['temp']}" if r["temp"] else r["method"]
        count[group] = count.get(group, 0) + 1
        r["label"] = f"{group}_s{r['seed'] or count[group]}"
    return sorted(runs, key=lambda r: r["label"])


def select(records, val_data):
    """Select best candidate generated by LLM"""
    unique = {}
    for r in records:
        if (
            r.get("valid") and (r.get("evaluation") or {}).get("score") is not None
        ):  # valid candidate with train score - remove duplicates
            behaviour = tuple(x["bins_used"] for x in r["evaluation"]["results"])
            unique.setdefault(
                behaviour, r
            )  # records are in generation order - keep earliest
    shortlist = sorted(unique.values(), key=lambda r: r["evaluation"]["score"])[
        :TOP_K
    ]  # select top k lowest train scores
    best, best_val = None, float("inf")
    for r in shortlist:
        res = run_candidate(
            r["candidate_code"], val_data, timeout=TIMEOUT
        )  # select cand. with best validation score
        if res.get("status") == "ok" and res["score"] < best_val:
            best, best_val = r, res["score"]
    return best


def bins_per_family(result):
    """Summary metrics per family.
    {family: (mean % excess, total bins)} from an evaluation result."""
    df = pd.DataFrame(result["results"])
    return df.groupby("family", sort=False).agg(
        excess=("score", "mean"), bins=("bins_used", "sum")
    )


def ms_per_instance(code, data):
    """Time taken for heuristic to pack 1 instance (take fastest of 3 runs)"""
    times = []
    for _ in range(3):
        res = [run_candidate(code, data[s], timeout=TIMEOUT) for s in TEST_SPLITS]
        n = sum(len(r["results"]) for r in res)
        times.append(1000 * sum(r["total_runtime"] for r in res) / n)
    return min(times)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--runs-dir", default=str(ROOT / "outputs" / "final_experiment"))
    p.add_argument("--prefix", default="final")
    p.add_argument("--out-dir", default=None)
    args = p.parse_args()

    runs = find_runs(args.runs_dir, args.prefix)
    if not runs:
        raise SystemExit(f"No candidates_{args.prefix}_*.jsonl in {args.runs_dir}")
    out_dir = Path(args.out_dir or ROOT / "outputs" / "final_eval" / args.prefix)
    (out_dir / "heuristics").mkdir(parents=True, exist_ok=True)
    print(f"Runs: {[r['label'] for r in runs]}")

    data = {s: load_dataset(s) for s in ("val", *TEST_SPLITS)}

    # ---------- baselines ----------
    heuristics = {
        "FF": first_fit,
        "BF": best_fit,
        "ABFF": load_tuned_ab_first_fit(
            str(ROOT / "outputs" / "final_data" / "ab_params.json")
        ),
    }
    results = {
        name: {s: evaluate(fn, data[s]) for s in TEST_SPLITS}
        for name, fn in heuristics.items()
    }
    bf_ms = ms_per_instance(STARTING_PROGRAM, data)

    # ---------- select and test 1 heuristic per run ----------
    cost_rows = []
    for r in runs:
        chosen = select(r["records"], data["val"])
        calls = [c for c in r["records"] if c["generation"] > 0]
        valid = sum(bool(c.get("valid")) for c in calls)
        row = {
            "run": r["label"],
            "selection_temperature": r["temp"],
            "calls": len(calls),
            "invalid": len(calls) - valid,
            "tokens": r["records"][-1][
                "cumulative_tokens"
            ], 
            "usd": round(sum(c.get("api_cost") or 0.0 for c in calls), 4),
            "selected_generation": chosen["generation"] if chosen else None,
        }
        if chosen:
            code = chosen["candidate_code"]
            (out_dir / "heuristics" / f"{r['label']}.py").write_text(
                code, encoding="utf-8"
            )
            results[r["label"]] = {
                s: run_candidate(code, data[s], timeout=TIMEOUT) for s in TEST_SPLITS
            }
            ms = ms_per_instance(code, data)
            row["ms_per_instance"] = round(ms, 3)
            row["time_vs_bf"] = round(ms / bf_ms, 2)
        cost_rows.append(row)

    # ---------- tables ----------
    excess, delta = {}, {}
    bf = {s: bins_per_family(results["BF"][s]) for s in TEST_SPLITS}
    for name, res in results.items():
        if any(res[s].get("status") != "ok" for s in TEST_SPLITS):
            print(f"{name} failed on a test split; left out of the tables")
            continue
        fam = pd.concat({s: bins_per_family(res[s]) for s in TEST_SPLITS})
        bf_fam = pd.concat(bf)
        excess[name] = fam["excess"]
        delta[name] = fam["bins"] - bf_fam["bins"]
    excess = pd.DataFrame(excess).round(3).rename_axis(["split", "family"])
    delta = pd.DataFrame(delta).rename_axis(["split", "family"])
    costs = pd.DataFrame(cost_rows)

    excess.to_csv(out_dir / "table_excess_by_family.csv")
    delta.to_csv(out_dir / "table_bins_vs_bestfit.csv")
    costs.to_csv(out_dir / "table_cost.csv", index=False)

    # ---------- figure 1: bins vs Best Fit ----------
    fig, ax = plt.subplots(figsize=(11, 4.8))
    families = [f for _, f in delta.index]
    x = range(len(families))
    series = [("ABFF", "gray", "x", -0.25)] + [
        (r["label"], COLORS[r["method"]], "o", 0.0 if r["method"] == "A" else 0.25)
        for r in runs
        if r["label"] in delta
    ]
    shown = set()
    for label, color, marker, offset in series:
        name = "ABFF (tuned baseline)" if label == "ABFF" else f"Method {label.rsplit('_s', 1)[0]}"
        ax.scatter(
            [i + offset for i in x],
            delta[label],
            color=color,
            marker=marker,
            s=36,
            zorder=3,
            label=None if name in shown else name,
        )
        shown.add(name)
    ax.set_yscale("symlog", linthresh=10)
    ax.axhline(0, color="black", linewidth=0.8)
    ax.axvline(
        sum(s == "in-test" for s, _ in delta.index) - 0.5, color="gray", linestyle=":"
    )
    ax.set_xticks(list(x))
    ax.set_xticklabels(families, rotation=30, ha="right")
    ax.set_ylabel("Total bins minus Best Fit\n(symlog; below 0 = fewer bins)")
    ax.set_title(
        "Bins relative to Best Fit (left: in-distribution test, right: out-of-distribution test)"
    )
    ax.grid(True, axis="y", alpha=0.3)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(out_dir / "fig_bins_vs_bf.png", dpi=300)
    plt.close(fig)

    # ---------- figure 2: best-so-far vs tokens ----------
    fig, ax = plt.subplots(figsize=(9, 4.8))
    for i, r in enumerate(runs):
        xs, ys, best = [], [], float("inf")
        for c in r["records"]:
            score = (c.get("evaluation") or {}).get("score")
            if c.get("valid") and score is not None:
                best = min(best, score)
                xs.append(c.get("cumulative_tokens") or 0)
                ys.append(best)
        ax.step(
            xs,
            ys,
            where="post",
            color=COLORS[r["method"]],
            linestyle=["-", "--", ":"][i % 3],
            label=f"Method {r['label']}",
        )
    ax.set_xlabel("Cumulative tokens")
    ax.set_ylabel("Best-so-far train score\n(% excess over lower bound)")
    ax.grid(True, alpha=0.3)
    ax.legend(frameon=False)
    fig.tight_layout()
    fig.savefig(out_dir / "fig_best_so_far.png", dpi=300)
    plt.close(fig)

    pd.set_option("display.width", 200)
    print("\n% excess over lower bound\n", excess.to_string())
    print("\nTotal bins minus Best Fit\n", delta.to_string())
    print(
        f"\nCost (Best Fit: {bf_ms:.3f} ms per instance)\n",
        costs.to_string(index=False),
    )
    print(f"\nSaved to {out_dir}")


